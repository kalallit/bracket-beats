const dicts: Record<Lang, Record<Key, string>> = { pt, en };

export function lang(): Lang {
  const setting = vscode.workspace.getConfiguration('bracketBeats').get<string>('language', 'auto');
  if (setting === 'pt' || setting === 'en') { return setting; }
  return (vscode.env?.language ?? 'en').toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

/** t('rec.andMore', 'Bonobo', 3) → "Bonobo e mais 3 que ouves" */
export function t(key: Key, ...args: (string | number)[]): string {
  const s = dicts[lang()][key] ?? pt[key] ?? key;
  return s.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ''));
}
